/**
 * Classify door styles as solid paint or wood-grain stain and propose each
 * door's own hex. Dry-run by default. Nothing is written to a database.
 *
 *   pnpm exec tsx scripts/door-swatch-hex-dry-run.ts
 *   pnpm exec tsx scripts/door-swatch-hex-dry-run.ts --catalog path/to/styles.json
 *
 * --apply is refused. The owner applies docs/proofs/swatch-hex/apply.sql by hand
 * after reviewing it. That file is generated commented-out on purpose.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { deltaE2000Hex } from "../shared/ciede2000";
import { doorInstanceFinish } from "../shared/doorInstanceFinish";
import { nearestBrandSwatch, planDoorFinish, type DoorFinishInput } from "../shared/doorFinishTint";

type StyleRow = DoorFinishInput & { id?: number; styleCode?: string | null; doorStyle?: string | null };

const outDir = path.resolve("docs/proofs/swatch-hex");

function arg(name: string): string | null {
  const index = process.argv.indexOf(name);
  return index >= 0 ? process.argv[index + 1] ?? null : null;
}

function loadStyles(file: string): StyleRow[] {
  const parsed = JSON.parse(readFileSync(file, "utf8")) as StyleRow[];
  return Array.isArray(parsed) ? parsed : [];
}

function sqlString(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

function main() {
  if (process.argv.includes("--apply")) {
    console.error("Refusing to write. Review docs/proofs/swatch-hex/apply.sql and run it by hand.");
    process.exit(2);
  }
  const catalog = arg("--catalog") ?? path.resolve("/tmp/fe/cabinet-frontend/shared/fixtures/doorStyleSideCatalog.json");
  const styles = loadStyles(catalog);
  const lines = [
    "| id | style | category | treatment | own hex | brand snap avoided | delta to snap | neighbor door hex |",
    "| --- | --- | --- | --- | --- | --- | --- | --- |",
  ];
  const sql = [
    "-- NOT APPLIED. Generated by scripts/door-swatch-hex-dry-run.ts.",
    "-- Review each row. Uncomment only the rows you approve.",
    "-- Schema columns come from docs/sql/0244_door_finish_category.tidb.sql and must exist first.",
    "-- Solid paint stores the door's own hex. It is not a brand swatch.",
    "-- Wood grain stores the stain hex and keeps the grain texture.",
    "",
  ];
  let paint = 0;
  let stain = 0;
  for (const style of styles) {
    const plan = planDoorFinish(style);
    const here = doorInstanceFinish({ placementUid: `style-${style.id ?? style.ourName}`, position: "0,0", pieceIndex: 0 }, style);
    const beside = doorInstanceFinish({ placementUid: `style-${style.id ?? style.ourName}`, position: "24,0", pieceIndex: 1 }, style);
    if (plan.finishCategory === "paint") paint += 1;
    else stain += 1;
    const snap = nearestBrandSwatch(plan.ownHex);
    const delta = deltaE2000Hex(plan.ownHex, snap);
    const treatment = plan.usesGrain ? "wood grain + stain tint" : "opaque solid";
    lines.push(`| ${style.id ?? ""} | ${style.aliasName || style.ourName || ""} | ${plan.finishCategory} | ${treatment} | ${plan.ownHex} | ${snap} | ${delta == null ? "" : delta.toFixed(1)} | ${beside.solidHex} |`);
    if (style.id != null) {
      sql.push(`-- ${style.aliasName || style.ourName} → ${treatment}`);
      sql.push(`-- UPDATE cabinet_dealz.door_styles SET renderHex = ${sqlString(plan.ownHex)}, finishCategory = ${sqlString(plan.finishCategory)} WHERE id = ${style.id} AND ourName = ${sqlString(style.ourName ?? "")};`);
    }
    void here;
  }
  mkdirSync(outDir, { recursive: true });
  const stone = styles.find((style) => /stone gray/i.test(`${style.aliasName ?? ""} ${style.ourName ?? ""}`));
  const stonePlan = stone ? planDoorFinish(stone) : null;
  const header = [
    "# Door finish classification (dry run)",
    "",
    "No database writes. Solid paint is an opaque hex of that door's own color. Wood grain keeps the grain and a stain tint. Adjacent doors get a different seeded tone. Gray is not snapped to a brand swatch.",
    "",
    `Styles classified: ${styles.length}. Solid paint: ${paint}. Wood grain / stain: ${stain}.`,
    stonePlan
      ? `Stone Gray (${stone?.id ?? ""}) is ${stonePlan.finishCategory}, ${stonePlan.usesGrain ? "grain" : "opaque solid"} ${stonePlan.ownHex}. The old nearest brand swatch is ${nearestBrandSwatch(stonePlan.ownHex)} and is not used.`
      : "Stone Gray was not in the catalog file.",
    "",
    ...lines,
    "",
  ];
  writeFileSync(path.join(outDir, "report.md"), header.join("\n"));
  writeFileSync(path.join(outDir, "apply.sql"), sql.join("\n") + "\n");
  console.log(`Wrote ${styles.length} rows (${paint} paint, ${stain} stain) to ${outDir}`);
}

main();

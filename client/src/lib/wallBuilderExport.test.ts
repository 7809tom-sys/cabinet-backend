import { describe, expect, it } from "vitest";
import { buildWallBuilderExportSvg } from "./wallBuilderExport";
import { appendWallBuilderSegment, type WallBuilderSegment } from "./polygonRoom";

function measuredPath(): WallBuilderSegment[] {
  let segments: WallBuilderSegment[] = [];
  segments = appendWallBuilderSegment(segments, 101, "start");
  segments = appendWallBuilderSegment(segments, 78, "right45");
  return segments;
}

describe("Continuous Wall Builder exports", () => {
  it("builds a standalone measured room-layout SVG in the selected rotated view", () => {
    const document = buildWallBuilderExportSvg(measuredPath(), 90, 108);
    expect(document).toMatchObject({ width: 1400, height: 1000 });
    expect(document.svg).toContain("CabinetDealz Room Layout");
    expect(document.svg).toContain("VIEW 90°");
    expect(document.svg).toContain("Wall 1 · 101&quot;");
    expect(document.svg).toContain("Wall 2 · 78&quot;");
    expect(document.svg).toContain("108&quot; wall height");
    expect(document.svg).toContain("Open connected wall path");
    expect(document.svg).toContain("Generated by CabinetDealz 3D Designer");
  });

  it("labels a completed four-wall outline as a closed room", () => {
    let segments: WallBuilderSegment[] = [];
    segments = appendWallBuilderSegment(segments, 120, "start");
    segments = appendWallBuilderSegment(segments, 96, "right90");
    segments = appendWallBuilderSegment(segments, 120, "right90");
    segments = appendWallBuilderSegment(segments, 96, "right90");
    const document = buildWallBuilderExportSvg(segments, 0, 96);
    expect(document.svg).toContain("4 walls");
    expect(document.svg).toContain("432&quot; total");
    expect(document.svg).toContain("Closed room");
    expect(document.svg).toMatch(/<path d="[^"]+ Z" fill="#d4a75a"/);
  });

  it("requires at least one measured wall", () => {
    expect(() => buildWallBuilderExportSvg([], 0, 96)).toThrow(/Add at least one wall/i);
  });
});
